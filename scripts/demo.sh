#!/usr/bin/env bash
# Bring up a complete local Tastelog with no paid keys:
#   local Supabase (Postgres, PostgREST, Auth, Storage) via the Supabase CLI,
#   the reconstructed schema + every migration, a demo login, three sample
#   recipes, and env files that point the API and web app at it with the
#   deterministic Claude stub (no Anthropic key, no network).
#
# Usage: make demo        (then follow the printed next steps)
# Needs: docker (running), supabase CLI, psql, curl. Safe to re-run.
#
# Everything here targets the local stack the CLI starts on this machine;
# nothing reads your .env or talks to a hosted project.

set -euo pipefail

REPO="$(cd "$(dirname "$0")/.." && pwd)"
cd "$REPO"

DEMO_EMAIL="demo@tastelog.local"
DEMO_PASSWORD="demo-password"

for tool in docker supabase psql curl; do
  command -v "$tool" >/dev/null 2>&1 || { echo "missing: $tool" >&2; exit 1; }
done
docker info >/dev/null 2>&1 || { echo "docker is not running" >&2; exit 1; }

KEYS="supabase/signing_keys.json"
if [ ! -s "$KEYS" ]; then
  echo "== generating a local ES256 signing key ($KEYS, gitignored) =="
  # The CLI reads the file named in config.toml before generating, so it
  # must exist as a JSON array; --append then writes the new key into it.
  echo '[]' > "$KEYS"
  supabase gen signing-key --algorithm ES256 --append
fi

echo "== starting local Supabase (first run pulls images) =="
supabase start

# API_URL, ANON_KEY, SERVICE_ROLE_KEY, DB_URL, STUDIO_URL ... as shell variables.
eval "$(supabase status -o env)"

echo "== schema =="
# apply.sh ledgers each migration as it lands, so the last one in the ledger
# means the whole chain is in. A database that has tables but not that entry
# is an interrupted bootstrap: refuse rather than seed on top of it.
LAST_MIGRATION="$(basename "$(ls migrations/*.sql | tail -1)" .sql)"
if psql "$DB_URL" -Atc "SELECT 1 FROM supabase_migrations.schema_migrations WHERE version='2000000000_$LAST_MIGRATION'" 2>/dev/null | grep -q 1; then
  echo "   already applied, skipping"
elif psql "$DB_URL" -Atc "SELECT 1 FROM information_schema.tables WHERE table_schema='public' AND table_name='recipes'" | grep -q 1; then
  echo "partial install: public.recipes exists but $LAST_MIGRATION is not in the migration ledger (an earlier bootstrap was interrupted)." >&2
  echo "recover with: supabase db reset && make demo   (resets the LOCAL demo database only)" >&2
  exit 1
else
  db/bootstrap/apply.sh "$DB_URL"
fi

echo "== demo user $DEMO_EMAIL =="
status=$(curl -s -o /dev/null -w "%{http_code}" -X POST "$API_URL/auth/v1/admin/users" \
  -H "apikey: $SERVICE_ROLE_KEY" -H "Authorization: Bearer $SERVICE_ROLE_KEY" \
  -H "Content-Type: application/json" \
  -d "{\"email\":\"$DEMO_EMAIL\",\"password\":\"$DEMO_PASSWORD\",\"email_confirm\":true}")
case "$status" in
  200|201) echo "   created" ;;
  422)     echo "   already exists" ;;
  *)       echo "   auth admin API returned HTTP $status" >&2; exit 1 ;;
esac

echo "== sample recipes =="
psql "$DB_URL" -v ON_ERROR_STOP=1 -q < db/bootstrap/demo_seed.sql

echo "== env files =="
cat > .env.demo <<ENV
# Generated by scripts/demo.sh for the LOCAL stack. Copy to .env to use.
SUPABASE_URL=$API_URL
SUPABASE_SERVICE_KEY=$SERVICE_ROLE_KEY
SUPABASE_ANON_KEY=$ANON_KEY
# Any non-empty value: the deterministic stub never calls Anthropic.
ANTHROPIC_API_KEY=demo
# Read from the process environment, not this file: run the API with
# make demo-api, which exports .env before starting uvicorn.
ANTHROPIC_STUB_MODE=deterministic
TEST_USER_ID=00000000-0000-0000-0000-000000000000
DEV_AUTH_BYPASS=false
ENVIRONMENT=development
LOG_LEVEL=INFO
CORS_ORIGINS='["http://localhost:3000"]'
ENV
cat > tastelog-web/.env.demo.local <<ENV
# Generated by scripts/demo.sh for the LOCAL stack. Copy to .env.local to use.
NEXT_PUBLIC_API_BASE_URL=http://localhost:8000
NEXT_PUBLIC_SUPABASE_URL=$API_URL
NEXT_PUBLIC_SUPABASE_ANON_KEY=$ANON_KEY
ENV

cat <<NEXT

Local stack is up.

  cp .env.demo .env && make demo-api                              # API on http://localhost:8000
  cp tastelog-web/.env.demo.local tastelog-web/.env.local
  (cd tastelog-web && npm run dev)                                # web on http://localhost:3000

  login:   $DEMO_EMAIL / $DEMO_PASSWORD
  studio:  $STUDIO_URL
  stop:    supabase stop
NEXT
